def init_cam(sda=22, scl=23, pwm_pin=11, pwm_freq_khz=37000, test_pattern=False):
    camera.set_pwm_pin(pwm_pin)
    camera.set_i2c_pins(sda, scl)
    camera.init_cam() # Initializes bus
    
    # Write the base registers
    camera.write_registers(REGS)

    # === JPEG VGA 640x480 mode configuration ===

    # VGA 640x480 window/crop/output (resolution registers, PLL-independent)
    camera.write_register(0x3820, 0x41) # TIMING_TC_REG20 (subsample)
    camera.write_register(0x3821, 0x27) # TIMING_TC_REG21 (mirror + JPEG enable bit5)
    camera.write_register(0x3814, 0x31) # X_INCREMENT
    camera.write_register(0x3815, 0x31) # Y_INCREMENT

    # Input window
    camera.write_register(0x3800, 0x00)
    camera.write_register(0x3801, 0x00)
    camera.write_register(0x3802, 0x00)
    camera.write_register(0x3803, 0x04)
    camera.write_register(0x3804, 0x0a)
    camera.write_register(0x3805, 0x3f)
    camera.write_register(0x3806, 0x07)
    camera.write_register(0x3807, 0x9b)

    # Output size: 640x480
    camera.write_register(0x3808, 0x02) # X_OUTPUT_SIZE_H (640)
    camera.write_register(0x3809, 0x80) # X_OUTPUT_SIZE_L
    camera.write_register(0x380a, 0x01) # Y_OUTPUT_SIZE_H (480)
    camera.write_register(0x380b, 0xe0) # Y_OUTPUT_SIZE_L

    # Timing
    camera.write_register(0x380c, 0x07) # X_TOTAL_SIZE_H
    camera.write_register(0x380d, 0x68) # X_TOTAL_SIZE_L
    camera.write_register(0x380e, 0x04) # Y_TOTAL_SIZE_H
    camera.write_register(0x380f, 0x38) # Y_TOTAL_SIZE_L

    # ISP offsets
    camera.write_register(0x3810, 0x00) # X_OFFSET_H
    camera.write_register(0x3811, 0x10) # X_OFFSET_L
    camera.write_register(0x3812, 0x00) # Y_OFFSET_H
    camera.write_register(0x3813, 0x06) # Y_OFFSET_L
    time.sleep_ms(50)

    # JPEG format configuration
    camera.write_register(0x3002, 0x00) # Release format/JPEG block resets
    camera.write_register(0x3006, 0xff) # Enable ALL clocks including JPEG
    camera.write_register(0x501F, 0x00) # FORMAT_CTRL: YUV422
    camera.write_register(0x4300, 0x30) # FORMAT_CTRL00: YUV422 YUYV byte order
    camera.write_register(0x4407, 0x20) # JPEG quality scale (moderate)
    camera.write_register(0x460b, 0x35) # JPEG stream marker enable
    camera.write_register(0x471c, 0x50) # DVP/JPEG path control
    camera.write_register(0x4713, 0x03) # JPEG mode 3
    camera.write_register(0x5001, 0xa3) # ISP_CONTROL_01
    camera.write_register(0x3503, 0x00) # AEC_PK_MANUAL

    # VFIFO size (match VGA output)
    camera.write_register(0x4602, 0x02) # VFIFO_X_SIZE_H (640)
    camera.write_register(0x4603, 0x80) # VFIFO_X_SIZE_L
    camera.write_register(0x4604, 0x01) # VFIFO_Y_SIZE_H (480)
    camera.write_register(0x4605, 0xe0) # VFIFO_Y_SIZE_L
    time.sleep_ms(50)

    # PLL configuration for 37MHz XCLK
    camera.write_register(0x3039, 0x00) # SC_PLL_CONTRL_5
    camera.write_register(0x3034, 0x1A) # SC_PLL_CONTRL_0
    camera.write_register(0x3035, 0x21) # SC_PLL_CONTRL_1 (sys_div=2)
    camera.write_register(0x3036, 0x2D) # SC_PLL_CONTRL_2 (mult=45)
    camera.write_register(0x3037, 0x13) # SC_PLL_CONTRL_3 (prediv=3)
    camera.write_register(0x3108, 0x16) # SYSTEM_ROOT_DIVIDER
    camera.write_register(0x3824, 0x10) # PCLK_RATIO (ratio=16)
    camera.write_register(0x460c, 0x22) # VFIFO_CTRL0C
    camera.write_register(0x3103, 0x13) # SCCB_SYSTEM_CTRL1
    camera.write_register(0x300e, 0x58) # DVP control

    # JPEG compression enable + PCLK polarity
    camera.write_register(0x3821, 0x26) # compression enable
    camera.write_register(0x4740, 0x21) # CLOCK_POL_CONTROL: active-high PCLK, VSYNC inverted

    # Release all blocks from reset
    camera.write_register(0x3000, 0x00)
    camera.write_register(0x3002, 0x00)
    
    if test_pattern:
        camera.write_register(0x503D, 0xC0) # TEST_COLOR_BAR
    else:
        camera.write_register(0x503D, 0x00)

    time.sleep_ms(50)
    print("JPEG camera initialization complete!")